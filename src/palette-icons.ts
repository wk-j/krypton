export type PaletteIconName = keyof typeof ICON_BODY;

/** Parsed-once icon nodes; every use is a clone. */
const templates = new Map<PaletteIconName, SVGElement>();

/** A fresh `<svg class="krypton-search-palette__icon">` for `name`, hidden from
 *  AT: the label beside it already says what the command does. */
export function paletteIcon(name: PaletteIconName): SVGElement {
  let tpl = templates.get(name);
  if (!tpl) {
    const holder = document.createElement('div');
    holder.innerHTML =
      `<svg class="krypton-search-palette__icon" viewBox="0 0 24 24" aria-hidden="true">${ICON_BODY[name]}</svg>`;
    tpl = holder.firstElementChild as SVGElement;
    templates.set(name, tpl);
  }
  return tpl.cloneNode(true) as SVGElement;
}
