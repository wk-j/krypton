export type PaletteIconName = keyof typeof ICON_BODY;

/** Parsed-once icon nodes; every use is a clone. */
const templates = new Map<PaletteIconName, SVGElement>();

/** A fresh `<svg class="${className}">` for `name` — a Commands-row icon unless
 *  the caller names its own class. Hidden from AT: the label beside it already
 *  says what the command does, and the which-key emblem is decoration. */
export function paletteIcon(name: PaletteIconName, className = 'krypton-search-palette__icon'): SVGElement {
  let tpl = templates.get(name);
  if (!tpl) {
    const holder = document.createElement('div');
    holder.innerHTML = `<svg viewBox="0 0 24 24" aria-hidden="true">${ICON_BODY[name]}</svg>`;
    tpl = holder.firstElementChild as SVGElement;
    templates.set(name, tpl);
  }
  const icon = tpl.cloneNode(true) as SVGElement;
  icon.setAttribute('class', className);
  return icon;
}
